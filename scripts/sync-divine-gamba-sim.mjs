#!/usr/bin/env node
/*
 * Copies the Divine Gamba simulation into the Edge Function bundle.
 *
 * The simulation is written once, in src/divine-gamba/sim/, and run twice:
 * in the browser and in supabase/functions/divine-gamba-settle. The Supabase
 * CLI bundles only what is under supabase/functions/, so the modules are
 * copied to supabase/functions/_shared/divine-gamba-sim/ and committed there.
 * tests/divineGambaSim.test.ts fails when the copy is stale, so a change to
 * the simulation that forgets this script cannot reach either side alone.
 *
 *   node scripts/sync-divine-gamba-sim.mjs          # write the copy
 *   node scripts/sync-divine-gamba-sim.mjs --check  # exit 1 if stale
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
export const SOURCE_DIRECTORY = path.join(root, 'src', 'divine-gamba', 'sim')
export const TARGET_DIRECTORY = path.join(root, 'supabase', 'functions', '_shared', 'divine-gamba-sim')

const BANNER = [
  '// GENERATED by scripts/sync-divine-gamba-sim.mjs from src/divine-gamba/sim/.',
  '// Edit the source and run the script; tests/divineGambaSim.test.ts fails when this copy is stale.',
  '',
].join('\n')

/** The modules that ship: every source file that is not a test. */
export function sourceModules() {
  return readdirSync(SOURCE_DIRECTORY)
    .filter((entry) => entry.endsWith('.ts') && !entry.endsWith('.test.ts'))
    .sort()
}

export function expectedCopy(module) {
  return BANNER + readFileSync(path.join(SOURCE_DIRECTORY, module), 'utf8')
}

export function staleModules() {
  const stale = []
  for (const module of sourceModules()) {
    let current = null
    try {
      current = readFileSync(path.join(TARGET_DIRECTORY, module), 'utf8')
    } catch {
      current = null
    }
    if (current !== expectedCopy(module)) {
      stale.push(module)
    }
  }
  let extra = []
  try {
    extra = readdirSync(TARGET_DIRECTORY).filter((entry) => !sourceModules().includes(entry))
  } catch {
    extra = []
  }
  return [...stale, ...extra]
}

function sync() {
  rmSync(TARGET_DIRECTORY, { recursive: true, force: true })
  mkdirSync(TARGET_DIRECTORY, { recursive: true })
  for (const module of sourceModules()) {
    writeFileSync(path.join(TARGET_DIRECTORY, module), expectedCopy(module))
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  if (process.argv.includes('--check')) {
    const stale = staleModules()
    if (stale.length > 0) {
      console.error(`Stale Divine Gamba simulation copy: ${stale.join(', ')}. Run node scripts/sync-divine-gamba-sim.mjs.`)
      process.exit(1)
    }
    console.log('The Divine Gamba simulation copy is current.')
  } else {
    sync()
    console.log(`Copied ${sourceModules().length} modules to ${path.relative(root, TARGET_DIRECTORY)}.`)
  }
}
